"""Compare the integer emulator (and the float reference) against v2e events (roadmap 2.6).

    python scripts/compare_vs_v2e.py --clip clip.mp4 --v2e clip_events.txt --theta-ln 0.2 --out docs/results/v2e_cmp

v2e must be run on the SAME clip with `--dvs_text`, `--pos_thres/--neg_thres` = theta-ln and
`--disable_slomo` if you skipped SuperSloMo. The text file has one event per line:
`t_seconds x y polarity` (v2e README). v2e resolution may differ from 128x128: events are scaled
to the emulator grid by x * 128 / v2e_width, so pass --v2e-width/--v2e-height if you did not
resize the clip to 128x128 for v2e.

Metrics per frame interval: event count (v2e, float ref, int model), ON fraction, and the Pearson
correlation of the signed event-count images (ON minus OFF) between the models and v2e.
"""
import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from model.emulator_int import EmuConfig, emulate  # noqa: E402
from model.emulator_ref import emulate_float  # noqa: E402
from model.event_format import unpack  # noqa: E402
from model.log_lut import theta_from_ln  # noqa: E402
from model.video_io import read_video  # noqa: E402


def load_v2e_text(path, w, h, size=128):
    a = np.loadtxt(path, comments="#", ndmin=2)
    t, x, y, p = a[:, 0], a[:, 1], a[:, 2], a[:, 3]
    x = np.clip((x * size / w).astype(int), 0, size - 1)
    y = np.clip((y * size / h).astype(int), 0, size - 1)
    return t, x, y, (p > 0).astype(int)


def signed_images(t, x, y, p, n_frames, dt, size=128):
    img = np.zeros((n_frames, size, size))
    cnt = np.zeros(n_frames)
    on = np.zeros(n_frames)
    # events generated by frame k lie in ((k-1)*dt, k*dt], so they belong to frame index ceil(t/dt)
    k = np.clip(np.ceil(t / dt - 1e-9).astype(int), 0, n_frames - 1)
    np.add.at(img, (k, y, x), np.where(p > 0, 1.0, -1.0))
    np.add.at(cnt, k, 1)
    np.add.at(on, k, p > 0)
    return img, cnt, on


def corr(a, b):
    a, b = a.ravel() - a.mean(), b.ravel() - b.mean()
    d = np.sqrt((a * a).sum() * (b * b).sum())
    return float((a * b).sum() / d) if d > 0 else float("nan")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--clip", required=True)
    ap.add_argument("--v2e", required=True)
    ap.add_argument("--theta-ln", type=float, default=0.2)
    ap.add_argument("--fps", type=float, default=30.0)
    ap.add_argument("--v2e-width", type=int, default=128)
    ap.add_argument("--v2e-height", type=int, default=128)
    ap.add_argument("--mode", choices=["step", "reset"], default="step")
    ap.add_argument("--out", default="docs/results/v2e_cmp")
    a = ap.parse_args()

    frames, fps = read_video(a.clip, 128, a.fps)
    n, dt = len(frames), 1.0 / fps
    theta = theta_from_ln(a.theta_ln)
    ev_int = emulate(frames, EmuConfig(theta=theta, mode=a.mode, period_ticks=int(round(1e4 / fps))))
    ii = np.zeros((n, 128, 128))
    ci = np.zeros(n)
    oi = np.zeros(n)
    for k, w in enumerate(ev_int):
        if len(w):
            u = unpack(w)
            np.add.at(ii[k], (u["y"], u["x"]), np.where(u["pol"] == 1, 1.0, -1.0))
            ci[k], oi[k] = len(w), u["pol"].sum()
    ef = emulate_float(frames, fps=fps, theta_ln=a.theta_ln)
    imf, cf, of = signed_images(ef["t"], ef["x"], ef["y"], ef["pol"], n, dt)
    tv, xv, yv, pv = load_v2e_text(a.v2e, a.v2e_width, a.v2e_height)
    imv, cv, ov = signed_images(tv, xv, yv, pv, n, dt)   # v2e time 0 = first frame

    print("theta = %d LSB (%.3f ln)  mode=%s  frames=%d @ %.1f fps" % (theta, a.theta_ln, a.mode, n, fps))
    print("total events:  v2e %d   float ref %d   int model %d" % (cv.sum(), cf.sum(), ci.sum()))
    print("ON fraction:   v2e %.3f  float ref %.3f  int model %.3f"
          % (ov.sum() / max(cv.sum(), 1), of.sum() / max(cf.sum(), 1), oi.sum() / max(ci.sum(), 1)))
    ks = [k for k in range(1, n) if cv[k] > 0 and ci[k] > 0]
    ci_corr = [corr(ii[k], imv[k]) for k in ks]
    cf_corr = [corr(imf[k], imv[k]) for k in ks]
    print("event-image correlation with v2e (mean over %d frames): int %.3f   float ref %.3f"
          % (len(ks), np.nanmean(ci_corr), np.nanmean(cf_corr)))

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 2, figsize=(11, 3.6))
    ax[0].plot(cv, label="v2e")
    ax[0].plot(cf, label="float ref")
    ax[0].plot(ci, label="int model")
    ax[0].set_xlabel("frame")
    ax[0].set_ylabel("events per frame")
    ax[0].legend()
    ax[1].plot(ks, ci_corr, label="int vs v2e")
    ax[1].plot(ks, cf_corr, label="float ref vs v2e")
    ax[1].set_xlabel("frame")
    ax[1].set_ylabel("event-image correlation")
    ax[1].legend()
    fig.tight_layout()
    fig.savefig(out / "compare.png", dpi=130)
    print("saved", out / "compare.png")


if __name__ == "__main__":
    main()
